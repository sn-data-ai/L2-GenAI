from google.colab import userdata
from langchain_openai import ChatOpenAI
import tiktoken

# 1. Fetch the key securely
openai_api_key = userdata.get('OPENAI_API_KEY')

# 2. Set up the local token encoder
# Using 'cl100k_base' as a reliable proxy for modern token counting
encoder = tiktoken.get_encoding("cl100k_base")

# 3. Define prompt and calculate local input tokens
prompt = "What is the capital of France"
input_tokens = len(encoder.encode(prompt))
print(f"--- Local Token Analysis Before Request ---")
print(f"Input Prompt: '{prompt}'")
print(f"Local Input Token Count: {input_tokens}\n")

# 4. Initialize and invoke model
model = ChatOpenAI(
    model="gpt-5.4-nano",
    api_key=openai_api_key
)

print("Sending request to OpenAI...")
response = model.invoke(prompt)

# 5. Extract output and calculate local output tokens
output_text = response.content
output_tokens = len(encoder.encode(output_text))

print(f"\n--- Model Response ---")
print(output_text)

print(f"\n--- Local Token Analysis After Request ---")
print(f"Local Output Token Count: {output_tokens}")
print(f"Total Local Session Tokens: {input_tokens + output_tokens}")

