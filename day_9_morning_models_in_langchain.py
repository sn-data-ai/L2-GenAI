from google.colab import userdata
from ollama import Client

# Fetch the API key securely from Colab Secrets
ollama_api_key = userdata.get('OLLAMA_API_KEY')

# Initialize the Ollama Cloud Client
client = Client(
    host="https://ollama.com",
    headers={
        "Authorization": f"Bearer {ollama_api_key}"
    }
)

# Execute the chat completion call
response = client.chat(
    model="gpt-oss:20b-cloud",
    messages=[
        {"role": "user", "content": prompt}
    ]
)

print("The response from Ollama cloud model is:\n")
#print(response)

# Uncomment the line below if you only want to extract the clean message body text
